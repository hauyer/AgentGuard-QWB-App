def render_report_pdf(report: dict, meta: dict) -> bytes:
    """App-layer PDF export. Renders report fields as-is; never alters metrics
    and never infers new causal conclusions."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        title=f"调查报告 {_esc(report.get('run_id', 'unknown'))}",
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleCN", parent=styles["Title"], fontSize=16, leading=20)
    h2 = ParagraphStyle("H2CN", parent=styles["Heading2"], fontSize=12, leading=16)
    body = ParagraphStyle("BodyCN", parent=styles["BodyText"], fontSize=9, leading=13)
    mono = ParagraphStyle("MonoCN", parent=body, fontName="Courier", fontSize=8)

    story: list = [Paragraph("AgentGuard-QWB-App 调查报告", title_style), Spacer(1, 4)]
    story.append(Paragraph(f"run_id: {_esc(report.get('run_id', '—'))}", mono))
    story.append(Paragraph(f"request_id: {_esc(report.get('request_id', '—'))}", mono))
    story.append(Paragraph(f"experiment_id: {_esc(report.get('experiment_id', '—'))}", mono))
    story.append(Paragraph(f"scenario_id: {_esc(report.get('scenario_id', '—'))}", mono))
    story.append(
        Paragraph(
            f"status: {_esc(report.get('status', '—'))} · policy_profile: {_esc(report.get('policy_profile', '—'))}",
            body,
        )
    )
    story.append(Paragraph(f"created_at: {_esc(report.get('created_at', '—'))}", body))
    story.append(Spacer(1, 6))

    story.append(Paragraph("风险发现", h2))
    findings = report.get("findings", [])
    if not findings:
        story.append(Paragraph("（无）", body))
    for finding in findings:
        if not isinstance(finding, dict):
            continue
        evidence_ids = ", ".join(str(item) for item in finding.get("evidence_ids", []))
        story.append(
            Paragraph(
                f"• {_esc(finding.get('finding_id', '?'))} [{_esc(finding.get('severity', '?'))}] "
                f"{_esc(finding.get('risk_type', '?'))} — {_esc(finding.get('summary', ''))} "
                f"(evidence: {_esc(evidence_ids)})",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("证据摘要", h2))
    evidence = report.get("evidence", [])
    if not evidence:
        story.append(Paragraph("（无）", body))
    for item in evidence:
        if not isinstance(item, dict):
            continue
        story.append(
            Paragraph(
                f"• {_esc(item.get('evidence_id', '?'))} — level={_esc(item.get('evidence_level', '?'))} "
                f"verification={_esc(item.get('verification_status', '?'))}",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("防御候选汇总", h2))
    candidates = report.get("defense_candidates", [])
    if not candidates:
        story.append(Paragraph("（无）", body))
    for item in candidates:
        if not isinstance(item, dict):
            continue
        story.append(
            Paragraph(
                f"• {_esc(item.get('candidate_id', '?'))} — status={_esc(item.get('status', '?'))} "
                f"execution_supported={_esc(item.get('execution_supported', False))}",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("已知限制", h2))
    limitations = report.get("limitations", [])
    if not limitations:
        story.append(Paragraph("（无）", body))
    for limitation in limitations:
        story.append(Paragraph(f"• {_esc(limitation)}", body))
    story.append(Spacer(1, 6))

    source_note = report.get("source_note") or meta.get("source")
    if source_note:
        story.append(Paragraph("结果来源", h2))
        story.append(Paragraph(_esc(source_note), body))
    story.append(Spacer(1, 8))
    story.append(
        Paragraph(
            "本 PDF 由应用层生成，仅排版上述字段；未改变底层指标，不推断新的因果结论。"
            " Generated by the application layer: metrics unchanged; no new causal conclusions.",
            ParagraphStyle("FooterCN", parent=body, textColor="#64748b", fontSize=7),
        )
    )

    doc.build(story)
    payload = buffer.getvalue()
    if len(payload) > MAX_PDF_BYTES:
        raise ReportsServiceError(500, "PDF_TOO_LARGE", "生成的 PDF 超出 4 MiB 上限")
    return payload


def render_investigation_loop_report_pdf(report: dict) -> bytes:
    """Render the same live loop-report object used by JSON export.

    STSong-Light is ReportLab's standard Simplified Chinese CID font. It keeps
    Chinese readable without bundling a third-party font file; Paragraphs and
    table rows flow across pages, and all upstream strings are XML-escaped.
    """
    font_name = "STSong-Light"
    try:
        if font_name not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(UnicodeCIDFont(font_name))
    except Exception as exc:  # noqa: BLE001 - fail explicitly when CJK support is unavailable
        raise ReportsServiceError(
            503, "REPORT_CHINESE_FONT_UNAVAILABLE", "当前运行环境无法加载中文 PDF 字体。"
        ) from exc

    buffer = io.BytesIO()
    report_id = report.get("loop", {}).get("loop_id", "未提供")
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        topMargin=17 * mm,
        bottomMargin=18 * mm,
        leftMargin=17 * mm,
        rightMargin=17 * mm,
        title=f"调查报告 {report_id}",
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "InvestigationReportTitleCN", parent=styles["Title"], fontName=font_name,
        fontSize=16, leading=22, wordWrap="CJK",
    )
    heading_style = ParagraphStyle(
        "InvestigationReportHeadingCN", parent=styles["Heading2"], fontName=font_name,
        fontSize=11, leading=16, spaceBefore=8, spaceAfter=4, wordWrap="CJK",
    )
    body_style = ParagraphStyle(
        "InvestigationReportBodyCN", parent=styles["BodyText"], fontName=font_name,
        fontSize=8.5, leading=12, wordWrap="CJK",
    )
    json_style = ParagraphStyle(
        "InvestigationReportJsonCN", parent=body_style, fontSize=7, leading=9,
        leftIndent=3 * mm, wordWrap="CJK",
    )
    story: list = [
        Paragraph("AgentGuard-QWB-App 调查报告", title_style),
        Paragraph(f"数据模式：{_esc(report.get('data_mode', '未提供'))}", body_style),
        Paragraph(f"生成时间：{_esc(report.get('generated_at', '未提供'))}", body_style),
        Spacer(1, 5),
    ]

    sections = (
        ("项目与调查基本信息", {"project": report.get("project"), "investigation": report.get("investigation")}),
        ("模型与运行环境", {
            key: report.get("investigation", {}).get(key)
            for key in ("model_id", "runtime_id", "mode", "scenario_id", "run_id", "experiment_id")
        }),
        ("Loop 状态与停止原因", report.get("loop")),
        ("风险发现与调查假设", report.get("risk_analysis")),
        ("多轮调查决策", report.get("decisions")),
        ("证据变化", report.get("evidence_changes")),
        ("预算消耗", report.get("budget")),
        ("防御候选与实际验证状态", report.get("defense")),
        ("策略评价关联", {
            "evaluation": report.get("strategy_evaluation"),
            "note": report.get("strategy_evaluation_note"),
        }),
        ("数据来源", report.get("data_sources")),
        ("研究限制", report.get("limitations")),
    )
    for title, value in sections:
        story.append(Paragraph(_esc(title), heading_style))
        if value is None:
            story.append(Paragraph("未提供", body_style))
            continue
        try:
            serialized = json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)
        except (TypeError, ValueError) as exc:
            raise ReportsServiceError(
                502, "REPORT_SERIALIZATION_FAILED", "调查报告包含无法序列化的数据。"
            ) from exc
        for line in serialized.splitlines() or [""]:
            story.append(Paragraph(_esc(line) or "&nbsp;", json_style))

    def footer(canvas, page_doc) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColorRGB(0.35, 0.4, 0.46)
        canvas.drawRightString(A4[0] - 17 * mm, 9 * mm, f"Page {page_doc.page}")
        canvas.restoreState()

    try:
        doc.build(story, onFirstPage=footer, onLaterPages=footer)
    except ReportsServiceError:
        raise
    except Exception as exc:  # noqa: BLE001 - convert renderer failures into API errors
        raise ReportsServiceError(500, "REPORT_PDF_RENDER_FAILED", "无法生成调查报告 PDF。") from exc
    payload = buffer.getvalue()
    if len(payload) > MAX_PDF_BYTES:
        raise ReportsServiceError(413, "REPORT_TOO_LARGE", "生成的 PDF 超出 4 MiB 上限。")
    return payload


def _to_service_error(exc: AgentGuardError) -> ReportsServiceError:
    code = exc.code
    status_code = exc.status_code or 502
    if code == "WARDEN_NOT_CONFIGURED":
        status_code = 503
    return ReportsServiceError(status_code, code, str(exc), exc.request_id)
