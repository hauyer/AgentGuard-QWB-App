"""Experiment comparison, reports and experience centre (B6).

Comparison data must come from verifiable experiment reports. No data means
no fabricated trend charts: live mode reports 503 EXPERIMENTS_UNAVAILABLE
because AgentGuard's public API only exposes single-report reads. PDF export
is generated by the application layer without changing underlying metrics or
inferring new causal conclusions.
"""

from __future__ import annotations

import io
import logging
from xml.sax.saxutils import escape as xml_escape

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from app.core.data_mode import DataMode, effective_data_mode
from app.integrations.agentguard_client import AgentGuardClient, AgentGuardError
from app.services.demo_service import DemoService

logger = logging.getLogger(__name__)

MAX_PDF_BYTES = 4 * 1024 * 1024

EXPERIMENTS_OPERATION = "GET /v1/experiments"
COMPARE_OPERATION = "POST /v1/experiments/compare"


def _esc(value: object) -> str:
    """Escape a field for reportlab's mini-HTML parser.

    Paragraph interprets XML-ish markup, so any upstream/user-controlled value
    (run_id, finding summaries, metadata strings) must be entity-escaped before
    interpolation - otherwise crafted content breaks rendering or injects
    markup into the exported PDF (B9 input safety).
    """
    return xml_escape(str(value))


class ReportsServiceError(RuntimeError):
    def __init__(self, status_code: int, code: str, message: str, request_id: str | None = None) -> None:
        self.status_code = status_code
        self.code = code
        self.message = message
        self.request_id = request_id
        super().__init__(message)


def _agentguard_reachable(client: AgentGuardClient) -> bool:
    try:
        client.health()
        return True
    except AgentGuardError:
        return False


def list_experiments(
    client: AgentGuardClient, demo: DemoService, *, mode_override: str | None
) -> tuple[dict, dict]:
    mode = effective_data_mode(mode_override, _agentguard_reachable(client))
    if mode == DataMode.LIVE:
        # C2 read-only experiment index (published at pinned 907aa19). Items
        # carry data_source/evidence_level/metrics_available verbatim - the BFF
        # never invents metrics when upstream reports metrics_available=false.
        operations = client.discover_operations()
        if not operations.get(EXPERIMENTS_OPERATION):
            raise ReportsServiceError(
                503, "EXPERIMENTS_UNAVAILABLE",
                "AgentGuard pinned 版本未发布实验索引接口（GET /v1/experiments）；"
                "不虚构趋势数据（QWB-INT-006）。")
        try:
            payload = client.list_experiments()
        except AgentGuardError as exc:
            raise _to_service_error(exc) from exc
        return payload, {
            "data_mode": "live",
            "capability": "available",
            "source_note": "实验列表来自 AgentGuard C2 只读实验索引；metrics_available=false 的条目不含指标。",
        }
    if mode in (DataMode.RECORDED, DataMode.SYNTHETIC):
        return demo.list_experiments(), demo.meta_for("experiments.json")
    raise ReportsServiceError(503, "API_UNAVAILABLE", "AgentGuard 不可达且未启用演示模式")


def compare_experiments(
    client: AgentGuardClient,
    demo: DemoService,
    *,
    mode_override: str | None,
    run_ids: list[str],
) -> tuple[dict, dict]:
    """Controlled comparison. Comparability is checked before any delta is
    computed: same scenario, metrics actually available, and synthetic runs are
    never mixed into a series with non-synthetic evidence. Incomparable input
    returns the reason instead of a fabricated improvement rate."""
    if len(run_ids) < 2:
        raise ReportsServiceError(422, "COMPARISON_NEEDS_TWO", "实验对比至少需要两个 run_id")
    mode = effective_data_mode(mode_override, _agentguard_reachable(client))
    if mode != DataMode.LIVE:
        raise ReportsServiceError(
            503, "COMPARISON_LIVE_ONLY",
            "实验对比仅在 Live 模式可用；演示数据不参与对比统计。")
    operations = client.discover_operations()
    if not operations.get(COMPARE_OPERATION):
        raise ReportsServiceError(
            503, "COMPARISON_UNAVAILABLE",
            "AgentGuard pinned 版本未发布实验对比接口（POST /v1/experiments/compare）。")
    try:
        index = client.list_experiments(limit=200)
        items = {item.get("run_id"): item for item in index.get("items", []) if item.get("run_id")}
        missing = [run_id for run_id in run_ids if run_id not in items]
        if missing:
            raise ReportsServiceError(422, "RUN_NOT_INDEXED",
                                      f"以下 run_id 不在实验索引中：{missing}")
        entries = [items[run_id] for run_id in run_ids]
        scenarios = {item.get("scenario_id") for item in entries}
        evidence_levels = {item.get("evidence_level") for item in entries}
        issues: list[str] = []
        if len(scenarios) > 1:
            issues.append(f"场景不一致: {sorted(str(s) for s in scenarios)}")
        no_metrics = [item.get("run_id") for item in entries if not item.get("metrics_available")]
        if no_metrics:
            issues.append(f"以下 run 无可用指标（metrics_available=false）: {no_metrics}")
        if "synthetic" in evidence_levels and evidence_levels != {"synthetic"}:
            issues.append(f"合成数据与真实证据混入同一对比系列: {sorted(str(e) for e in evidence_levels)}")
        if issues:
            return {
                "comparable": False,
                "reasons": issues,
                "entries": [{k: item.get(k) for k in
                             ("run_id", "experiment_id", "scenario_id", "evidence_level",
                              "data_source", "metrics_available", "execution_status")}
                            for item in entries],
            }, {"data_mode": "live", "capability": "available"}
        payload = client.compare_experiments(run_ids)
        return {"comparable": True, **payload}, {"data_mode": "live", "capability": "available"}
    except AgentGuardError as exc:
        raise _to_service_error(exc) from exc
    except ReportsServiceError:
        raise


def get_report(
    client: AgentGuardClient, demo: DemoService, *, mode_override: str | None, run_id: str
) -> tuple[dict, dict]:
    mode = effective_data_mode(mode_override, _agentguard_reachable(client))
    if mode == DataMode.LIVE:
        try:
            return client.get_report(run_id), {"data_mode": "live"}
        except AgentGuardError as exc:
            raise _to_service_error(exc) from exc
    if mode in (DataMode.RECORDED, DataMode.SYNTHETIC):
        report = demo.get_report(run_id)
        if report is None:
            raise ReportsServiceError(404, "NOT_FOUND", f"报告不存在：{run_id}")
        return report, demo.meta_for("reports.json")
    raise ReportsServiceError(503, "API_UNAVAILABLE", "AgentGuard 不可达且未启用演示模式")


def list_experiences(
    client: AgentGuardClient, demo: DemoService, *, mode_override: str | None
) -> tuple[dict, dict]:
    mode = effective_data_mode(mode_override, _agentguard_reachable(client))
    if mode == DataMode.LIVE:
        try:
            return client.search_verified_experiences(), {"data_mode": "live"}
        except AgentGuardError as exc:
            raise _to_service_error(exc) from exc
    if mode in (DataMode.RECORDED, DataMode.SYNTHETIC):
        return demo.list_experiences(), demo.meta_for("experiences.json")
    raise ReportsServiceError(503, "API_UNAVAILABLE", "AgentGuard 不可达且未启用演示模式")


def render_report_pdf(report: dict, meta: dict) -> bytes:
    """App-layer PDF export. Renders report fields as-is; never alters metrics
    and never infers new causal conclusions."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        title=f"调查报告 {_esc(report.get('run_id', 'unknown'))}",
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleCN", parent=styles["Title"], fontSize=16, leading=20)
    h2 = ParagraphStyle("H2CN", parent=styles["Heading2"], fontSize=12, leading=16)
    body = ParagraphStyle("BodyCN", parent=styles["BodyText"], fontSize=9, leading=13)
    mono = ParagraphStyle("MonoCN", parent=body, fontName="Courier", fontSize=8)

    story: list = [Paragraph("AgentGuard-QWB-App 调查报告", title_style), Spacer(1, 4)]
    story.append(Paragraph(f"run_id: {_esc(report.get('run_id', '—'))}", mono))
    story.append(Paragraph(f"request_id: {_esc(report.get('request_id', '—'))}", mono))
    story.append(Paragraph(f"experiment_id: {_esc(report.get('experiment_id', '—'))}", mono))
    story.append(Paragraph(f"scenario_id: {_esc(report.get('scenario_id', '—'))}", mono))
    story.append(
        Paragraph(
            f"status: {_esc(report.get('status', '—'))} · policy_profile: {_esc(report.get('policy_profile', '—'))}",
            body,
        )
    )
    story.append(Paragraph(f"created_at: {_esc(report.get('created_at', '—'))}", body))
    story.append(Spacer(1, 6))

    story.append(Paragraph("风险发现", h2))
    findings = report.get("findings", [])
    if not findings:
        story.append(Paragraph("（无）", body))
    for finding in findings:
        if not isinstance(finding, dict):
            continue
        evidence_ids = ", ".join(str(item) for item in finding.get("evidence_ids", []))
        story.append(
            Paragraph(
                f"• {_esc(finding.get('finding_id', '?'))} [{_esc(finding.get('severity', '?'))}] "
                f"{_esc(finding.get('risk_type', '?'))} — {_esc(finding.get('summary', ''))} "
                f"(evidence: {_esc(evidence_ids)})",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("证据摘要", h2))
    evidence = report.get("evidence", [])
    if not evidence:
        story.append(Paragraph("（无）", body))
    for item in evidence:
        if not isinstance(item, dict):
            continue
        story.append(
            Paragraph(
                f"• {_esc(item.get('evidence_id', '?'))} — level={_esc(item.get('evidence_level', '?'))} "
                f"verification={_esc(item.get('verification_status', '?'))}",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("防御候选汇总", h2))
    candidates = report.get("defense_candidates", [])
    if not candidates:
        story.append(Paragraph("（无）", body))
    for item in candidates:
        if not isinstance(item, dict):
            continue
        story.append(
            Paragraph(
                f"• {_esc(item.get('candidate_id', '?'))} — status={_esc(item.get('status', '?'))} "
                f"execution_supported={_esc(item.get('execution_supported', False))}",
                body,
            )
        )
    story.append(Spacer(1, 6))

    story.append(Paragraph("已知限制", h2))
    limitations = report.get("limitations", [])
    if not limitations:
        story.append(Paragraph("（无）", body))
    for limitation in limitations:
        story.append(Paragraph(f"• {_esc(limitation)}", body))
    story.append(Spacer(1, 6))

    source_note = report.get("source_note") or meta.get("source")
    if source_note:
        story.append(Paragraph("结果来源", h2))
        story.append(Paragraph(_esc(source_note), body))
    story.append(Spacer(1, 8))
    story.append(
        Paragraph(
            "本 PDF 由应用层生成，仅排版上述字段；未改变底层指标，不推断新的因果结论。"
            " Generated by the application layer: metrics unchanged; no new causal conclusions.",
            ParagraphStyle("FooterCN", parent=body, textColor="#64748b", fontSize=7),
        )
    )

    doc.build(story)
    payload = buffer.getvalue()
    if len(payload) > MAX_PDF_BYTES:
        raise ReportsServiceError(500, "PDF_TOO_LARGE", "生成的 PDF 超出 4 MiB 上限")
    return payload


def _to_service_error(exc: AgentGuardError) -> ReportsServiceError:
    code = exc.code
    status_code = exc.status_code or 502
    if code == "WARDEN_NOT_CONFIGURED":
        status_code = 503
    return ReportsServiceError(status_code, code, str(exc), exc.request_id)
